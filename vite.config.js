import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import { readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const CLIENTS_DIR = fileURLToPath(new URL('./src/data/clients/', import.meta.url)).replace(/\\/g, '/');
const VIRTUAL_ID = 'virtual:wedding-clients';
const RESOLVED_ID = `\0${VIRTUAL_ID}`;

/** Client slugs = file names in src/data/clients (files starting with "_" are templates). */
export function listClients() {
  return readdirSync(CLIENTS_DIR)
    .filter((f) => f.endsWith('.js') && !f.startsWith('_'))
    .map((f) => f.slice(0, -3));
}

/**
 * Exposes `virtual:wedding-clients`: a lazy loader per client. With
 * VITE_CLIENT set, only that client is bundled, so a single-client build
 * never ships another client's data.
 */
function weddingClients(only) {
  return {
    name: 'wedding-clients',
    resolveId: (id) => (id === VIRTUAL_ID ? RESOLVED_ID : null),
    load(id) {
      if (id !== RESOLVED_ID) return null;
      const all = listClients();
      if (only && !all.includes(only)) {
        this.error(`VITE_CLIENT="${only}" has no matching file in src/data/clients/. Available: ${all.join(', ')}`);
      }
      const slugs = only ? [only] : all;
      const entries = slugs.map((s) => `  ${JSON.stringify(s)}: () => import(${JSON.stringify(`${CLIENTS_DIR}${s}.js`)})`);
      return `export const clients = {\n${entries.join(',\n')}\n};\nexport const lockedClient = ${JSON.stringify(only || null)};\n`;
    },
    configureServer(server) {
      // Pick up client files added or removed while the dev server runs.
      const refresh = (file) => {
        if (!file.replace(/\\/g, '/').includes('/src/data/clients/')) return;
        const mod = server.moduleGraph.getModuleById(RESOLVED_ID);
        if (mod) server.moduleGraph.invalidateModule(mod);
        server.ws.send({ type: 'full-reload' });
      };
      server.watcher.on('add', refresh);
      server.watcher.on('unlink', refresh);
    },
  };
}

// Relative base keeps asset paths working on Vercel (/), GitHub Pages
// (/<repo>/) and on every /<slug>/ page generated by scripts/postbuild.mjs.
export default defineConfig({
  plugins: [react(), weddingClients(process.env.VITE_CLIENT)],
  base: './',
});
